/**
 * Build data/*.json bundle and js/game-data-bundle.js.
 * JSON packs are the modding source of truth; edit data/*.json then run this script.
 * Run: node scripts/extract-game-data.mjs
 */
import fs from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const JS = join(ROOT, 'js');
const DATA = join(ROOT, 'data');

function readJson(path) {
  return JSON.parse(fs.readFileSync(path, 'utf8'));
}

const units = readJson(join(DATA, 'units.json'));
const buildings = readJson(join(DATA, 'buildings.json'));
const enemies = readJson(join(DATA, 'enemies.json'));
const strikes = readJson(join(DATA, 'strikes.json'));
const synergies = readJson(join(DATA, 'synergies.json'));

const pack = { units, buildings, enemies, strikes, synergies };

const bundle = `/** Auto-generated by scripts/extract-game-data.mjs — do not edit by hand */
const GameDataBundle = ${JSON.stringify(pack, null, 0)};
`;
fs.writeFileSync(join(JS, 'game-data-bundle.js'), bundle);

console.log('Rebuilt GameDataBundle:', {
  units: Object.keys(units).length,
  buildings: Object.keys(buildings).length,
  enemies: Object.keys(enemies).length,
  abilities: Object.keys(strikes.abilities || {}).length,
  spyActions: Object.keys(strikes.spyActions || {}).length,
  fxLife: Object.keys(strikes.fxLife || {}).length,
  synergies: synergies.length,
});
