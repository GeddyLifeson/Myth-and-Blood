#!/usr/bin/env node
/**
 * Prints the README key tables from the default key maps in js/hotkeys.js, so the manual
 * cannot drift from the game.
 *
 *   node scripts/gen-readme-keys.mjs           print the tables
 *   node scripts/gen-readme-keys.mjs --write   replace the block in README.md
 *   node scripts/gen-readme-keys.mjs --check   exit 1 if README.md is out of date
 *
 * The block in README.md sits between the two marker comments below.
 */
import { readFileSync, writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';
import vm from 'vm';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const START = '<!-- keys:start (generated by scripts/gen-readme-keys.mjs) -->';
export const END = '<!-- keys:end -->';

function loadHotkeys() {
  const sandbox = {};
  sandbox.globalThis = sandbox;
  vm.runInNewContext(readFileSync(join(ROOT, 'js', 'hotkeys.js'), 'utf8'), sandbox, {
    filename: 'hotkeys.js',
  });
  return sandbox.Hotkeys;
}

const cell = (s) => String(s).replace(/\|/g, '\\|');
const code = (keys) =>
  String(keys)
    .split(' ')
    .map((k) => (k === '`' ? '`` ` ``' : `\`${k}\``))
    .join(' ');

/** Keys as plain text (the first table); only the backtick itself needs code marks. */
const plain = (keys) =>
  String(keys)
    .split(' ')
    .map((k) => (k === '`' ? '`` ` ``' : k))
    .join(' ');

/** A Markdown table padded the way Prettier pads it. */
function table(head, rows) {
  const all = [head, ...rows].map((r) => r.map(cell));
  const w = head.map((_, i) => Math.max(3, ...all.map((r) => [...r[i]].length)));
  const line = (r) => `| ${r.map((c, i) => c + ' '.repeat(w[i] - [...c].length)).join(' | ')} |`;
  return [
    line(all[0]),
    `| ${w.map((n) => '-'.repeat(n)).join(' | ')} |`,
    ...all.slice(1).map(line),
  ];
}

/** Rows of one state, with the twenty recruit slots folded into one row. */
function rowsOf(H, state) {
  const first = H.keyLabel(H.SLOT_KEYS[0]);
  const last = H.keyLabel(H.SLOT_KEYS[H.SLOT_KEYS.length - 1]);
  const half = H.keyLabel(H.SLOT_KEYS[9]);
  const second = H.keyLabel(H.SLOT_KEYS[10]);
  let slots = false;
  const rows = [];
  for (const r of H.sheet(state, (b) => (b.action === 'deploySlot' ? '\u0000slot' : b.label))) {
    if (r.label === '\u0000slot') {
      if (!slots) {
        slots = true;
        rows.push({
          keys: `${first}–${half} ${second}–${last}`,
          label: 'Recruit: one key per unlocked troop, in panel order',
        });
      }
      continue;
    }
    rows.push(r);
  }
  return rows;
}

export function generate() {
  const H = loadHotkeys();
  const out = [];
  const base = rowsOf(H, 'night');
  out.push(`**${H.STATE_LABELS.night}** (the full field map)`, '');
  out.push(
    ...table(
      ['Key', 'Action'],
      base.map((r) => [plain(r.keys), r.label])
    )
  );

  const baseByKey = new Map(base.map((r) => [r.keys, r.label]));
  const others = H.STATES.filter((s) => s !== 'night');
  const rows = [];
  for (const state of others) {
    const here = rowsOf(H, state);
    const hereByKey = new Map(here.map((r) => [r.keys, r.label]));
    const changed = here.filter((r) => baseByKey.get(r.keys) !== r.label);
    const off = base.filter((r) => !hereByKey.has(r.keys));
    // A short map (menu, pause, spoils, after the battle) is listed whole.
    const whole = here.length <= 14;
    const shown = whole ? here : changed;
    const text = shown.map((r) => `${code(r.keys)} ${r.label}`).join('; ');
    const offText = whole
      ? 'Nothing else works'
      : off.length
        ? `Off: ${off.map((r) => code(r.keys)).join(' ')}`
        : 'Everything else as on the field';
    rows.push([H.STATE_LABELS[state], text || 'Same keys as the field', offText]);
  }
  out.push('', '**Other screens**', '');
  out.push(...table(['Screen', 'Keys', 'The rest'], rows));
  return out.join('\n');
}

/** The text between the markers in a README, or null. */
export function readBlock(readme) {
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  if (a < 0 || b < a) return null;
  return readme.slice(a + START.length, b).trim();
}

/** Ignore table padding, which the formatter owns. */
export const normalize = (s) =>
  s
    .replace(/-{3,}/g, '---')
    .replace(/[ \t]+/g, ' ')
    .replace(/ ?\n ?/g, '\n')
    .trim();

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = generate();
  const file = join(ROOT, 'README.md');
  if (process.argv.includes('--write') || process.argv.includes('--check')) {
    const readme = readFileSync(file, 'utf8');
    const block = readBlock(readme);
    if (block == null) {
      console.error('README.md has no key block markers');
      process.exit(1);
    }
    if (process.argv.includes('--check')) {
      if (normalize(block) !== normalize(text)) {
        console.error('README.md key tables are out of date: run with --write');
        process.exit(1);
      }
      console.log('README.md key tables are up to date');
    } else {
      const a = readme.indexOf(START) + START.length;
      const b = readme.indexOf(END);
      writeFileSync(file, `${readme.slice(0, a)}\n\n${text}\n\n${readme.slice(b)}`);
      console.log('README.md key tables written');
    }
  } else {
    console.log(text);
  }
}
